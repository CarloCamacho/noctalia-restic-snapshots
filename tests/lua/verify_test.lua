print("== IPC: single-flight")

do
  lsText = lsJson({ { "one.conf", "file", "/tmp/data/one.conf", 4 } })
  boot({ interval_minutes = 1440, verify_file_count = 1 }, { ["/tmp/data/one.conf"] = "same\n" })
  drain()

  -- While a job holds the guard.
  onIpc("backup-now")
  check("a backup is running", status().busy == true)
  onIpc("verify-restore")
  check("a verification is refused while a job is in flight",
    logCount("restic: rejected a job is already running") == 1,
    logCount("restic: rejected a job is already running"))
  exitJob('{"message_type":"summary","total_files_processed":1}\n', 0)

  -- While a verification is between "began" and "its job started" (no job holds the guard yet),
  -- the update() tick and a second IPC event must both be refused. The clock moves first: jobs
  -- derive their token from the clock, and a job started in the same millisecond as the finished
  -- backup would reuse its files.
  H.nowMs = H.nowMs + 1000
  onIpc("verify-restore")
  local starts = jobStarts()
  onIpc("verify-restore")
  check("a second on-demand verification is refused while one is starting",
    logCount("restic: rejected a verification is already running") == 1,
    logCount("restic: rejected a verification is already running"))
  update()
  check("the tick does not start a second verification in that window",
    jobStarts() == starts, jobStarts())
  drain()
  check("the verification still starts its job", jobsRunning("restore") == 1,
    jobsRunning("restore"))
end

