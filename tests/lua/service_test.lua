    scriptText():find("'--password-file'", 1, true) ~= nil
      and scriptText():find("secret", 1, true) == nil)
  exitJob('{"message_type":"summary","files_processed":1}\n', 0)

  starts = jobStarts()
  onIpc("restore", '{"snapshot":"abcdef12","target":"/etc"}')
  check("a restore outside the allow-list is refused", jobStarts() == starts, jobStarts())
  check("the refusal names the allowed roots",
    logCount("restic: rejected restore target must be inside") == 1)

  onIpc("restore", '{"snapshot":"../../etc", "target":"/tmp/restore"}')
  check("a restore with a bad snapshot id is refused", jobStarts() == starts, jobStarts())

  onIpc("diff", '{"from":"zzzzzzzz","to":"abcdef12"}')
  check("a diff with a non-hex id is refused", jobStarts() == starts, jobStarts())

  onIpc("ls", "")
  check("an empty payload is refused", jobStarts() == starts, jobStarts())

  onIpc("no-such-event", "{}")
  check("an unknown event is ignored", jobStarts() == starts and logCount("restic ipc error") == 0)
end

print("== payload shapes")

do
  boot({ interval_minutes = 5, job_timeout_minutes = 180 })
  drain()

  -- retention preview (contract 4.7: kind, at, ok, keepCount, removeCount, remove, truncated)
  onIpc("forget-dry-run")
  check("forget-dry-run starts a dry run",
    scriptText():find("'--dry-run'", 1, true) ~= nil and scriptText():find("'--prune'", 1, true) == nil)
  exitJob('{"keep":[{"id":"aaaa1111","short_id":"aaaa1111","time":"2026-09-08T13:36:42+00:00"}],'
    .. '"remove":[{"id":"bbbb2222","short_id":"bbbb2222","time":"2026-09-08T03:36:42+00:00"}],'
    .. '"reasons":{}}\n', 0)
  local preview = H.published["restic_job"]
  check("the retention preview publishes its shape",
    preview ~= nil and preview.kind == "forget-dry" and preview.ok == true
      and preview.keepCount == 1 and preview.removeCount == 1, preview and preview.kind)
  check("the retention preview lists what would go",
    preview.remove ~= nil and preview.remove[1] ~= nil and preview.remove[1].id == "bbbb2222"
      and preview.remove[1].shortId == "bbbb2222" and preview.remove[1].time ~= nil,
    preview.remove and preview.remove[1] and preview.remove[1].id)
  check("the retention preview is not truncated", preview.truncated == false)

  -- restore preview (contract 4.7: kind, at, ok, snapshot, target, files)
  onIpc("restore-dry-run", '{"snapshot":"abcdef12"}')
  check("the restore preview runs restic restore --dry-run",
    scriptText():find("'restore'", 1, true) ~= nil
      and scriptText():find("'--dry-run'", 1, true) ~= nil
      and scriptText():find("'/tmp/restore'", 1, true) ~= nil)
  exitJob('{"message_type":"summary","total_files":5,"files_restored":5,"total_bytes":2006,'
    .. '"bytes_restored":2006}\n', 0)
  local restored = H.published["restic_job"]
  check("the restore preview publishes its shape",
    restored ~= nil and restored.kind == "restore-dry" and restored.ok == true
      and restored.snapshot == "abcdef12" and restored.target == "/tmp/restore"
      and restored.files == 5, restored and (restored.kind .. " " .. tostring(restored.files)))

  -- the real restore, same guard
  onIpc("restore", '{"snapshot":"abcdef12","target":"/tmp/restore"}')
  check("the real restore is a plain restore",
    scriptText():find("'restore'", 1, true) ~= nil
      and scriptText():find("'--dry-run'", 1, true) == nil)
  exitJob('{"message_type":"summary","total_files":5,"files_restored":5}\n', 0)
  check("a finished restore notifies", logCount("notify: Restore complete") == 1)
  check("a finished restore is persisted", readState().lastRestoreAt ~= nil)

  -- files listing (contract 4.7: snapshot, entries, truncated, at, ok)
  onIpc("ls", '{"snapshot":"abcdef12"}')
  exitJob('{"message_type":"snapshot","id":"abcdef12"}\n'
    .. '{"name":"a.bin","type":"file","path":"/tmp/data/a.bin","size":2000}\n'
    .. '{"name":"sub","type":"dir","path":"/tmp/data/sub"}\n', 0)
  local files = H.published["restic_files"]
  check("the file listing publishes its shape",
    files ~= nil and files.snapshot == "abcdef12" and files.ok == true
      and files.truncated == false and files.at ~= nil, files and files.snapshot)
  check("the file listing carries path, type and size",
    files.entries[1].path == "/tmp/data/a.bin" and files.entries[1].type == "file"
      and files.entries[1].size == 2000,
    files.entries[1] and tostring(files.entries[1].path))

  -- diff (contract 4.7: from, to, added, removed, changed, truncated, at, ok)
  onIpc("diff", '{"from":"11111111","to":"abcdef12"}')
  exitJob('{"message_type":"change","path":"/tmp/data/new.bin","modifier":"+"}\n'
    .. '{"message_type":"change","path":"/tmp/data/gone.bin","modifier":"-"}\n'
    .. '{"message_type":"statistics","changed_files":0}\n', 0)
  local diff = H.published["restic_diff"]
  check("the diff publishes its shape",
    diff ~= nil and diff.from == "11111111" and diff.to == "abcdef12" and diff.ok == true
      and diff.added == 1 and diff.removed == 1 and diff.changed == 0 and diff.truncated == false,
    diff and tostring(diff.added))

  -- repository stats (contract 4.7: totalBytes, totalFileCount, snapshotsCount, updatedAt, ok)
  onIpc("stats")
  drain()
  local stats = H.published["restic_stats"]
  check("the stats card publishes its shape",
    stats ~= nil and stats.totalBytes == 1024 and stats.totalFileCount == 7
      and stats.snapshotsCount == 2 and stats.ok == true and stats.updatedAt ~= nil,
    stats and tostring(stats.totalBytes))

  -- init and unlock
  onIpc("unlock")
  check("unlock asks restic to drop every lock",
    scriptText():find("'unlock'", 1, true) ~= nil
      and scriptText():find("'--remove-all'", 1, true) ~= nil
      and scriptText():find("'--no-lock'", 1, true) == nil)
  exitJob('{"message_type":"summary","removed":1}\n', 0)
  drain()

  onIpc("init")
  check("init runs restic init", scriptText():find("'init'", 1, true) ~= nil)
  exitJob('{"message_type":"initialized","id":"abc","repository":"/tmp/repo"}\n', 0)
  check("a successful init clears initNeeded", status().initNeeded == false)
  check("a successful init notifies", logCount("notify: Restic repository initialised") == 1)

  -- job-log re-publishes the last job's log
  onIpc("job-log")
  local joblog = H.published["restic_joblog"]
  check("job-log republishes the last job's log",
    joblog ~= nil and joblog.kind == "init" and #joblog.lines == 1
      and joblog.lines[1]:find("initialized", 1, true) ~= nil, joblog and joblog.kind)
end

