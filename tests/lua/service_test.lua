print("== scheduled integrity checks")

do
  -- Never checked, interval set: due immediately, reading the first rotating slice. The backup
  -- interval is deliberately long so this timeline measures checks only -- `update()` runs both
  -- schedules and a backup would take the single-job guard first.
  boot({ interval_minutes = 1440, check_interval_hours = 1, check_subset = "1/4" })
  drain()
  update()
  check("a due check starts on the next tick", jobStarts() == 1, jobStarts())
  check("the check reads the first rotating slice",
    scriptText():find("'--read-data-subset=1/4'", 1, true) ~= nil, scriptText())
  check("the check is not a read-only call",
    scriptText():find("'--no-lock'", 1, true) == nil)
  local persisted = readState()
  check("the rotation advances so the next check reads elsewhere",
    persisted ~= nil and persisted.checkRotationIndex == 1, persisted and tostring(persisted.checkRotationIndex))

  exitJob('{"message_type":"summary","num_errors":0}\n', 0)
  local checks = status().checks
  check("the check result is published", checks ~= nil and checks.lastAt ~= nil
    and checks.lastOk == true and checks.numErrors == 0, checks and tostring(checks.lastOk))
  persisted = readState()
  check("the check time is persisted", persisted.lastCheckAt == math.floor(H.nowMs / 1000),
    persisted and tostring(persisted.lastCheckAt))

  update()
  check("a check that just ran is not due again", jobStarts() == 1, jobStarts())
  H.nowMs = (math.floor(H.nowMs / 1000) + 3600 + 1) * 1000
  update()
  check("a check is due after its interval", jobStarts() == 2, jobStarts())
  check("the rotation moves on to the next slice",
    scriptText():find("'--read-data-subset=2/4'", 1, true) ~= nil, scriptText())
  exitJob('{"message_type":"summary","num_errors":3}\n', 0)
  check("check errors are published", status().checks.numErrors == 3,
    tostring(status().checks.numErrors))

  -- Checks off: never run, whatever the clock says.
  boot({ interval_minutes = 1440, check_interval_hours = 0 })
  drain()
  H.nowMs = (NOW_SEC + 30 * 24 * 3600) * 1000
  update()
  check("scheduled checks are off when the interval is 0", jobsRunning("check") == 0, jobsRunning("check"))

  -- A percentage subset has no slots: it must not be turned into a full read.
  boot({ interval_minutes = 1440, check_interval_hours = 1, check_subset = "5%" })
  drain()
  update()
  check("a percentage subset is passed through unchanged",
    scriptText():find("'--read-data-subset=5%'", 1, true) ~= nil, scriptText())
end

